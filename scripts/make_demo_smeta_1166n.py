def build(path: Path) -> Path:
    wb = Workbook()
    ws = wb.active
    ws.title = "Смета 1166Н"
    header = ["Шифр расценки", "Наименование работ", "Ед. изм.", "Объём", "Цена, ₽"]
    ws.append(header)
    for cell in ws[1]:
        cell.font = Font(bold=True)
    for code, name, unit, qty, price in ROWS:
        ws.append([code, name, unit, qty, price])
    for col, width in zip("ABCDE", (20, 74, 10, 10, 12)):
        ws.column_dimensions[col].width = width
    ws.freeze_panes = "A2"
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


