"""Стенд: измеритель поведения моделей, который можно проверить сам.

Зачем отдельный пакет. `pto_agent/eval.py` отвечает на вопрос «не врёт ли наш агент».
Этот пакет отвечает на другой вопрос: **не врёт ли наш измерительный прибор**. Обычный
бенчмарк проверить нельзя: он говорит «модель набрала 87 %», и остаётся верить. Здесь
рядом с прогоном на настоящей модели живёт прогон на `MockModel` — OpenAI-совместимом
сервере с заранее известными ответами и заранее известными сбоями. Если прибор не
показывает эти сбои, прибор сломан.

Состав:

* `MockModel` — локальный HTTP-сервер `/v1/chat/completions` с управляемым поведением
  (правильный ответ, битый JSON, выдуманное число вместо «нет данных», обрыв по лимиту);
* `runner` — протокол прогона по правилам, а не «сделали 20 запросов»: блоки,
  интерливинг, все исходы сохраняются, таймауты не выбрасываются, метрика — доля годного
  результата **с первой попытки**;
* `report` — markdown и json с интервалом Уилсона, ограничениями и командой повтора.

    python3 -m pto_agent bench mock --out out/bench
"""
